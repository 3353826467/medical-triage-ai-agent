def profile_text(profile: dict) -> str:
    """把结构化患者信息渲染成提示片段。"""
    if not profile:
        return "（患者未提供基础信息）"
    mapping = {
        "age": "年龄",
        "gender": "性别",
        "duration": "病程",
        "history": "既往史",
        "allergy": "过敏史",
        "medication": "当前用药",
        "pregnancy": "妊娠状态",
    }
    parts = [f"{mapping.get(k, k)}：{v}" for k, v in profile.items() if v not in (None, "", [])]
    return "；".join(parts) if parts else "（患者未提供基础信息）"
